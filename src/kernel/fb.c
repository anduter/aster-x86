/* ---- 标准 VGA 8x8 字模：优先从 BIOS ROM（F000:FA6E）拷一份 ----
 * BIOS 里的字形比手写的规整得多，是 VGA 文本模式实际使用的字库。
 * ROM 里每行 bit7 在左，本驱动约定 bit0 在左，所以拷贝时逐字节翻转。
 * 探测失败（非 BIOS 环境/ROM 不可读）就继续用手写 font8x8。 */
static uint8_t bios_font[128][8];
static bool    bios_font_ok;

static uint8_t reverse_bits(uint8_t b)
{
    b = (uint8_t)(((b & 0xF0U) >> 4) | ((b & 0x0FU) << 4));
    b = (uint8_t)(((b & 0xCCU) >> 2) | ((b & 0x33U) << 2));
    b = (uint8_t)(((b & 0xAAU) >> 1) | ((b & 0x55U) << 1));
    return b;
}

static void load_bios_font(void)
{
    const uint8_t *rom = (const uint8_t *)(uintptr_t)0x000FFA6EU;  /* F000:FA6E */
    const uint8_t *glyph_a = rom + ('A' * 8);
    int ones = 0, zeros = 0;

    /* 用 'A' 做探测：既要有实心像素也要有空白，否则认为 ROM 不可用 */
    for (int j = 0; j < 8; j++) {
        uint8_t r = glyph_a[j];
        if (r != 0x00U && r != 0xFFU) { ones++; }
        for (int i = 0; i < 8; i++) {
            if (r & (1U << i)) zeros++;
        }
    }
    if (ones < 4 || zeros < 8 || zeros > 56) return;

    for (uint32_t ch = 0; ch < 128U; ch++) {
        for (uint32_t j = 0; j < 8U; j++) {
            bios_font[ch][j] = reverse_bits(rom[ch * 8U + j]);
        }
    }
    bios_font_ok = true;
}

void fb_init(void)
{
    /* 真实参数来自加载器保存在 SYSINFO+0x400 的 VBE 模式信息块（见 sysinfo.asm）。
       过去这里写死 0xFD000000 / 1024x768 / 3072，只在 QEMU std VGA 的
       VBE 0x118 模式下成立；换显卡或换分辨率就会往错误的物理地址画图。 */
    fb_w     = *(volatile uint16_t *)(VBE_MODE + 0x12);   /* 横向分辨率     */
    fb_h     = *(volatile uint16_t *)(VBE_MODE + 0x14);   /* 纵向分辨率     */
    fb_bpp   = *(volatile uint8_t  *)(VBE_MODE + 0x19);   /* 每像素位数     */
    fb_pitch = *(volatile uint16_t *)(VBE_MODE + 0x10);   /* 每行字节数     */
    fb_addr  = *(volatile uint32_t *)(FB_ADDR);           /* 显存物理地址   */

    /* 兜底值：即使 VBE 探测失败，内核也能继续工作 */
    if (fb_w == 0U || fb_h == 0U) { fb_w = 1024U; fb_h = 768U; }
    if (fb_bpp == 0U)   { fb_bpp = 24U; }
    if (fb_pitch == 0U) { fb_pitch = (uint32_t)fb_w * (fb_bpp / 8U); }
    if (fb_addr == 0U)  { fb_addr = 0xFD000000U; }

    fb_size = fb_pitch * (uint32_t)fb_h;

    /* BGR 字节序：低字节=B，中间=G，高字节=R */
    rpos = 16U;
    gpos = 8U;
    bpos = 0U;

    load_bios_font();               /* 有 BIOS 字库就用更清晰的字形 */
    if (bios_font_ok) {
        kprintln("fb: using BIOS VGA 8x8 font (crisper glyphs)");
    } else {
        kprintln("fb: BIOS font unavailable, using built-in 8x8 font");
    }
}

void fb_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb_w || y >= fb_h)
        return;                 /* 超出屏幕范围直接忽略 */

    uint32_t offset = y * fb_pitch + x * (fb_bpp / 8U);
    uint8_t *ptr = (uint8_t *)(fb_addr + offset);

    if (fb_bpp == 32U)
    {
        /* 按 R/G/B 各自的位偏移组装像素值，兼容不同字节序 */
        uint8_t r = (color >> 16U) & 0xFFU;
        uint8_t g = (color >> 8U)  & 0xFFU;
        uint8_t b = color & 0xFFU;
        uint32_t pixval = ((uint32_t)r << rpos) | ((uint32_t)g << gpos) | ((uint32_t)b << bpos);
        *(volatile uint32_t *)ptr = pixval;
    }
    else if (fb_bpp == 24U)
    {
        ptr[0] = (uint8_t)color;
        ptr[1] = (uint8_t)(color >> 8U);
        ptr[2] = (uint8_t)(color >> 16U);
    }
    else if (fb_bpp == 16U)
    {
        uint16_t c16 = (uint16_t)(((color>>19U)<<11U) | ((color>>10U)<<5U) | (color>>3U));
        *(volatile uint16_t *)ptr = c16;
    }
}

void fb_fill_rect(uint32_t x0, uint32_t y0, uint32_t x1, uint32_t y1, uint32_t color)
{
    if (x0 > x1) { uint32_t t = x0; x0 = x1; x1 = t; }
    if (y0 > y1) { uint32_t t = y0; y0 = y1; y1 = t; }
    if (x1 > fb_w) x1 = fb_w;
    if (y1 > fb_h) y1 = fb_h;

    for (uint32_t y = y0; y < y1; y++) {
        for (uint32_t x = x0; x < x1; x++) {
            fb_pixel(x, y, color);
        }
    }
}

void fb_clear(uint32_t color)
{
    fb_fill_rect(0U, 0U, fb_w, fb_h, color);
}

void fb_char_scaled(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg,
                    uint32_t scale)
{
    uint32_t off = (uint32_t)(uint8_t)c - 0x20U;
    if ((uint8_t)c < 0x20U || (uint8_t)c > 0x7EU)
        return;
    if (scale == 0U) scale = 1U;

    for (uint32_t j = 0U; j < 8U; j++)
    {
        /* 优先用 BIOS 标准字模；没有就回退到手写字体 */
        uint8_t row = bios_font_ok ? bios_font[(uint8_t)c][j]
                                   : font8x8[off][j];
        for (uint32_t i = 0U; i < 8U; i++)
        {
            uint32_t color = (row & (1U << i)) ? fg : bg;

            /* 整数倍放大：每个字模像素画成 scale x scale 的方块 */
            for (uint32_t dy = 0U; dy < scale; dy++) {
                for (uint32_t dx = 0U; dx < scale; dx++) {
                    fb_pixel(x + i * scale + dx, y + j * scale + dy, color);
                }
            }
        }
    }
}

void fb_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg)
{
    fb_char_scaled(x, y, c, fg, bg, 1U);
}

void fb_text(uint32_t x, uint32_t y, const char *s, uint32_t fg, uint32_t bg)
{
    while (*s != '\0')
    {
        fb_char(x, y, *s, fg, bg);
        x += 8U;
        s++;
    }
}

void fb_hex32(uint32_t x, uint32_t y, uint32_t val, uint32_t fg, uint32_t bg)
{
    static const char hex[] = "0123456789ABCDEF";
    char buf[9];
    for(int i = 7; i >= 0; i--)
        buf[7-i] = hex[(val >> (i*4U)) & 0xFU];
    buf[8] = '\0';
    fb_text(x, y, buf, fg, bg);
}

void fb_hex64(uint32_t x, uint32_t y, uint64_t val, uint32_t fg, uint32_t bg)
{
    static const char hex[] = "0123456789ABCDEF";
    char buf[17];
    for(int i = 15; i >= 0; i--)
        buf[15-i] = hex[(val >> (i*4U)) & 0xFU];
    buf[16] = '\0';
    fb_text(x, y, buf, fg, bg);
}
