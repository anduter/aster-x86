static inline const u8 *aster_font_glyph(u8 ch)
{
    if (ch < ASTER_FONT_FIRST || ch > ASTER_FONT_LAST) {
        ch = '?';
    }
    return aster_font8x8[ch - ASTER_FONT_FIRST];
}

static inline u32 aster_draw__pitch(const struct aster_surface *s)
{
    return (s->pitch_px != 0) ? s->pitch_px : s->width;
}

static inline void aster_draw_pixel(struct aster_surface *s, i32 x, i32 y,
                                    u32 argb)
{
    if (s == NULL || s->pixels == NULL) {
        return;
    }
    if (x < 0 || y < 0 || (u32)x >= s->width || (u32)y >= s->height) {
        return;
    }
    s->pixels[(u32)y * aster_draw__pitch(s) + (u32)x] = argb;
}

static inline void aster_surface_clear(struct aster_surface *s, u32 argb)
{
    u32 y;
    u32 x;

    if (s == NULL || s->pixels == NULL) {
        return;
    }
    for (y = 0; y < s->height; y++) {
        u32 *row = s->pixels + (u64)y * aster_draw__pitch(s);

        for (x = 0; x < s->width; x++) {
            row[x] = argb;
        }
    }
}

static inline void aster_draw_fill(struct aster_surface *s, i32 x, i32 y,
                                   i32 w, i32 h, u32 argb)
{
    i64 x0;
    i64 y0;
    i64 x1;
    i64 y1;
    i64 yy;
    i64 xx;

    if (s == NULL || s->pixels == NULL || w <= 0 || h <= 0) {
        return;
    }
    x0 = x;
    y0 = y;
    x1 = (i64)x + (i64)w;
    y1 = (i64)y + (i64)h;
    if (x0 < 0) {
        x0 = 0;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (x1 > (i64)s->width) {
        x1 = (i64)s->width;
    }
    if (y1 > (i64)s->height) {
        y1 = (i64)s->height;
    }
    for (yy = y0; yy < y1; yy++) {
        u32 *row = s->pixels + (u64)yy * aster_draw__pitch(s);

        for (xx = x0; xx < x1; xx++) {
            row[(u32)xx] = argb;
        }
    }
}

/* 1 像素空心矩形（自动裁剪；w/h 含边）。 */
static inline void aster_draw_rect(struct aster_surface *s, i32 x, i32 y,
                                   i32 w, i32 h, u32 argb)
{
    if (w <= 0 || h <= 0) {
        return;
    }
    aster_draw_fill(s, x, y, w, 1, argb);
    aster_draw_fill(s, x, y + h - 1, w, 1, argb);
    aster_draw_fill(s, x, y, 1, h, argb);
    aster_draw_fill(s, x + w - 1, y, 1, h, argb);
}

static inline void aster_draw_char(struct aster_surface *s, i32 x, i32 y,
                                   u8 ch, u32 fg, u32 bg)
{
    const u8 *glyph = aster_font_glyph(ch);
    u32 row;
    u32 col;

    for (row = 0; row < ASTER_FONT_H; row++) {
        u8 bits = glyph[row];

        for (col = 0; col < ASTER_FONT_W; col++) {
            u32 color = (((bits >> col) & 1u) != 0u) ? fg : bg;

            aster_draw_pixel(s, x + (i32)col, y + (i32)row, color);
        }
    }
}

/* 逐字符画；不处理 '\n'（alpha 只做单行）。越界字符画 '?'。 */
static inline void aster_draw_text(struct aster_surface *s, i32 x, i32 y,
                                   const char *text, u32 fg, u32 bg)
{
    i32 cx = x;
    u64 i = 0;

    if (s == NULL || text == NULL) {
        return;
    }
    while (text[i] != '\0') {
        aster_draw_char(s, cx, y, (u8)text[i], fg, bg);
        cx += (i32)ASTER_FONT_W;
        i++;
    }
}

