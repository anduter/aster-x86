# =============================================================================
# sign_image.ps1 - 用 RSA-2048/SHA-256 对镜像签名，并生成内核 C 数组
#
#   - 签名格式：OpenSSL dgst -sha256 -sign，即 PKCS#1 v1.5 + SHA-256
#   - 输出 C：<prefix>_signature[256] / <prefix>_modulus[256]（大端字节）
#   - 私钥不进 git：keys/shell_private.pem 由本地生成（tools/gen-key.ps1）
#     或 CI secret 注入；仓库只保留 keys/shell_public.pem 与 keys/README.md
#
# 用法（通常由 build.ps1 调用）：
#   powershell -NoProfile -File sign_image.ps1 -Image obj/user_shell.elf `
#       -Key keys/shell_private.pem -Signature obj/shell.sig `
#       -OutC obj/shell_signature.c -Prefix shell
# =============================================================================
param(
    [Parameter(Mandatory=$true)][string]$Image,
    [Parameter(Mandatory=$true)][string]$Key,
    [Parameter(Mandatory=$true)][string]$Signature,
    [Parameter(Mandatory=$true)][string]$OutC,
    [string]$Prefix = 'shell'
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $Image)) { throw "sign_image: 镜像不存在：$Image" }
if (-not (Test-Path -LiteralPath $Key)) {
    throw @"
sign_image: 签名私钥不存在：$Key

私钥刻意不进 git（开源仓库不能带签名私钥）。二选一：
  1) 本地生成：powershell -NoProfile -File tools/gen-key.ps1
  2) CI/发布：从 secret（如 SIGNING_KEY_PEM）写入该路径后再构建
生成/轮换/CI 用法见 keys/README.md 与 SECURITY.md。
"@
}
if (-not (Get-Command openssl -ErrorAction SilentlyContinue)) {
    throw 'sign_image: 找不到 openssl（需要 OpenSSL 1.1+；Windows 可用 Git for Windows 自带的那份）'
}

& openssl dgst -sha256 -sign $Key -out $Signature $Image
if ($LASTEXITCODE -ne 0) { throw "openssl sign failed" }

$modLine = (& openssl rsa -in $Key -noout -modulus) -join "`n"
$modHex = ($modLine -replace '(?s).*Modulus\s*=\s*', '').Trim()
if ($modHex.Length -ne 512) { throw "unexpected RSA modulus size: $($modHex.Length)" }

$sigBytes = [IO.File]::ReadAllBytes((Resolve-Path $Signature))
if ($sigBytes.Length -ne 256) { throw "unexpected signature size: $($sigBytes.Length)" }

function Convert-HexToBytes([string]$hex) {
    $out = New-Object byte[] ($hex.Length / 2)
    for ($i = 0; $i -lt $out.Length; $i++) {
        $out[$i] = [Convert]::ToByte($hex.Substring($i * 2, 2), 16)
    }
    return $out
}

function Format-CArray([byte[]]$bytes) {
    $parts = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        $parts.Add(('0x{0:X2}' -f $bytes[$i]))
    }
    $lines = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $parts.Count; $i += 12) {
        $n = [Math]::Min(12, $parts.Count - $i)
        $lines.Add('    ' + (($parts.GetRange($i, $n) -join ', ')) + ',')
    }
    return ($lines -join "`n")
}

$modBytes = Convert-HexToBytes $modHex
$sigText = Format-CArray $sigBytes
$modText = Format-CArray $modBytes

$c = @"
/* Auto-generated by sign_image.ps1 from the build-time signing key.
 * 公钥模数在这里生成，不落源码树；私钥永不进 git（见 keys/README.md）。 */
const unsigned char ${Prefix}_signature[256] = {
$sigText
};
const unsigned char ${Prefix}_modulus[256] = {
$modText
};
"@

$dir = Split-Path -Parent $OutC
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
[IO.File]::WriteAllText($OutC, $c, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("[OK] signed {0} -> {1}" -f $Image, $OutC)
