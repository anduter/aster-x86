# gensyms.ps1 - generate a kernel symbol table (C source) from the ELF
# usage: gensyms.ps1 -Elf obj/kernel-pass1.elf -Out obj/symbols.c
param(
    [Parameter(Mandatory = $true)][string]$Elf,
    [Parameter(Mandatory = $true)][string]$Out
)

$ErrorActionPreference = 'Stop'
$nm = 'i686-elf-nm'

$lines = & $nm -n $Elf 2>$null
if ($LASTEXITCODE -ne 0) { throw "nm failed" }

$entries = @()
foreach ($line in $lines) {
    # format: "00100000 T func_name"
    if ($line -match '^([0-9a-fA-F]{8})\s+([Tt])\s+(\S+)$') {
        $addr = [Convert]::ToUInt32($matches[1], 16)
        $name = $matches[3]
        if ($addr -ge 0x100000) {
            $entries += [pscustomobject]@{ Addr = $addr; Name = $name }
        }
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* auto-generated by tools/gensyms.ps1 - do not edit */')
[void]$sb.AppendLine('#include "core/ksym.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const ksym_t ksym_table[] = {')
foreach ($e in $entries) {
    [void]$sb.AppendLine(('    {{ 0x{0:x8}U, "{1}" }},' -f $e.Addr, $e.Name))
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('')
[void]$sb.AppendLine(('const unsigned int ksym_count = {0}U;' -f $entries.Count))

[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host ("[OK] symbols: {0} entries -> {1}" -f $entries.Count, $Out)
